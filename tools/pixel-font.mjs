// кириллица, совпадающая по форме с латиницей
const SAME = { "А": "A", "В": "B", "Е": "E", "К": "K", "М": "M", "Н": "H", "С": "C", "Т": "T", "Р": "P" };

export const ADVANCE = 6; // ширина символа с пробелом, в пикселях шрифта

/** Текст пикселями: возвращает разметку <rect> (соседние пиксели в строке склеены). */
export function pixelText(str, ox, oy, s, color, shadow) {
  let out = shadow ? pixelText(str, ox + s, oy + s, s, shadow) : "";
  [...str].forEach((ch, i) => {
    const g = FONT[ch] ?? FONT[SAME[ch]];
    if (!g) throw new Error(`Нет глифа для «${ch}»`);
    g.forEach((row, y) => {
      let x = 0;
      while (x < row.length) {
        let run = 1;
        while (row[x + run] === row[x]) run++;
        if (row[x] === "#") {
          out += `<rect x="${ox + (i * ADVANCE + x) * s}" y="${oy + y * s}" width="${run * s}" height="${s}" fill="${color}"/>`;
        }
        x += run;
      }
    });
  });
  return out;
}

export const textWidth = (str, s) => [...str].length * ADVANCE * s - s;
